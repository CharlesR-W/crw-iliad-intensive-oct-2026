from pathlib import Path

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyArrowPatch, Rectangle  # noqa: E402

OUT = Path(__file__).resolve().parent
STEM = "slt2_free_energy_volume"

BLUE, ORANGE, GREY, INK = "#2b6cb0", "#c05621", "#8a8f98", "#1f2328"
plt.rcParams.update({
    "font.family": "STIXGeneral", "mathtext.fontset": "stix", "font.size": 12.5,
    "axes.edgecolor": INK, "axes.linewidth": 0.8, "text.color": INK,
    "axes.labelcolor": INK, "xtick.color": INK, "ytick.color": INK,
    "svg.fonttype": "path", "figure.facecolor": "white", "savefig.facecolor": "white",
})


def save(fig, name):
    fig.savefig(OUT / f"{STEM}_{name}.svg", bbox_inches="tight", pad_inches=0.05)
    plt.close(fig)


def bare(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


# ------------------------------------------------------------------ slicing
def slicing():
    w = np.linspace(-1, 1, 801)
    K = w**4
    t, dt, n = 0.20, 0.07, 12
    r0, r1 = t ** 0.25, (t + dt) ** 0.25

    fig, (ax, axw) = plt.subplots(1, 2, figsize=(6.4, 3.0), sharey=True,
                                  gridspec_kw={"width_ratios": [3.2, 1], "wspace": 0.08})
    ax.plot(w, K, color=INK, lw=1.6)
    ax.axhspan(t, t + dt, color=ORANGE, alpha=0.15, lw=0)
    ax.axhline(t, color=GREY, lw=0.8, ls="--")
    ax.text(-1.0, t - 0.025, r"$t$", va="top", ha="left", color=GREY)
    ax.text(-1.0, t + dt + 0.02, r"$t+dt$", va="bottom", ha="left", color=GREY)
    # sublevel set {K<t} on the w-axis
    ax.add_patch(Rectangle((-r0, -0.06), 2 * r0, 0.035, color=BLUE, lw=0))
    ax.fill_between(w, 0, np.minimum(K, t), where=np.abs(w) < r0, color=BLUE, alpha=0.10, lw=0)
    ax.annotate(r"$\{K<t\}$: prior mass $V(t)$", xy=(-0.3, -0.045), xytext=(-0.3, -0.13),
                ha="center", va="top", color=BLUE,
                arrowprops=dict(arrowstyle="-", color=BLUE, lw=0.8))
    # the slab {t < K < t+dt}
    for s in (-1, 1):
        ax.add_patch(Rectangle((s * r0 if s > 0 else -r1, -0.06), r1 - r0, 0.035, color=ORANGE, lw=0))
    ax.annotate(r"$\{t<K<t+dt\}$: mass $v(t)\,dt$", xy=((r0 + r1) / 2, -0.06), xytext=(1.0, -0.27),
                ha="right", va="top", color=ORANGE,
                arrowprops=dict(arrowstyle="-", color=ORANGE, lw=0.8, shrinkA=1, shrinkB=2, relpos=(0.93, 1.0)))
    ax.set_xlim(-1.05, 1.05); ax.set_ylim(-0.42, 1.02)
    ax.set_xticks([]); ax.set_yticks([])
    ax.set_xlabel(r"parameter $w$"); ax.set_ylabel(r"excess loss $K(w)=w^4$")
    bare(ax); ax.spines["bottom"].set_position(("data", 0))
    ax.xaxis.set_label_coords(0.5, -0.02)

    tt = np.linspace(0, 1.02, 300)
    axw.fill_betweenx(tt, 0, np.exp(-n * tt), color=GREY, alpha=0.25, lw=0)
    axw.plot(np.exp(-n * tt), tt, color=INK, lw=1.2)
    axw.axhspan(t, t + dt, color=ORANGE, alpha=0.15, lw=0)
    axw.axhline(t, color=GREY, lw=0.8, ls="--")
    axw.text(0.15, 0.62, "weight " + r"$e^{-nt}$" + "\n" + r"($n=%d$)" % n, ha="left", va="center", fontsize=11.5)
    axw.set_xlim(0, 1.1); axw.set_xticks([]); bare(axw)
    axw.spines["left"].set_visible(False); axw.tick_params(left=False)
    axw.spines["bottom"].set_position(("data", 0))
    save(fig, "slicing")


# ------------------------------------------------------------------ sublevel sets in 2-D
def sublevel2d():
    g = np.linspace(-1, 1, 241)
    A, B = np.meshgrid(g, g)
    cases = [
        (A**2 + B**2, r"$K=a^2+b^2$", r"$\lambda=1$  (bowl, $=d/2$)", r"$V=\pi t/4$"),
        (A**2 + B**4, r"$K=a^2+b^4$", r"$\lambda=3/4$", r"$V\propto t^{3/4}$"),
        ((A * B) ** 2, r"$K=(ab)^2$", r"$\lambda=1/2,\ m=2$", r"$V=\sqrt{t}\,(1+\frac{1}{2}\log\frac{1}{t})$"),
    ]
    ts = [4.0**-1, 4.0**-2, 4.0**-3]
    shades = ["#c9dcf0", "#7fa9d6", BLUE]
    fig, axs = plt.subplots(1, 3, figsize=(7.2, 2.9))
    for ax, (K, title, lam, vlaw) in zip(axs, cases):
        for t, c in zip(ts, shades):
            ax.contourf(A, B, K, levels=[-1, t], colors=[c])
            ax.contour(A, B, K, levels=[t], colors=[INK], linewidths=0.5)
        ax.add_patch(Rectangle((-1, -1), 2, 2, fill=False, ec=GREY, lw=0.8))
        ax.set_aspect("equal"); ax.set_xlim(-1.02, 1.02); ax.set_ylim(-1.02, 1.02); ax.axis("off")
        ax.set_title(title, fontsize=13, pad=4)
        ax.text(0, -1.13, lam, ha="center", va="top", fontsize=12.5)
        ax.text(0, -1.33, vlaw, ha="center", va="top", fontsize=12.5, color=BLUE)
    from matplotlib.patches import Patch
    handles = [Patch(color=c, label=lab) for c, lab in zip(shades, [r"$t=1/4$", r"$t=1/16$", r"$t=1/64$"])]
    fig.legend(handles=handles, loc="lower center", ncol=3, frameon=False, bbox_to_anchor=(0.5, -0.2),
               title=r"sublevel set $\{K<t\}$ (box = prior support $[-1,1]^2$)", title_fontsize=11.5)
    fig.subplots_adjust(wspace=0.12)
    save(fig, "sublevel2d")


# ------------------------------------------------------------------ log V against log t
def logV():
    t = np.logspace(-10, -0.3, 400)
    I = 1.7480383  # int_{-1}^1 sqrt(1-u^4) du
    curves = [  # exact V(t) for the uniform prior on [-1,1]^2 (t < 1)
        (np.pi * t / 4, r"$a^2+b^2$", 1.0, "1", GREY, -6.3),
        (0.5 * I * t**0.75, r"$a^2+b^4$", 0.75, r"\frac{3}{4}", ORANGE, -8.4),
        (0.5 * np.sqrt(t) * (-np.log(t)) + np.sqrt(t), r"$(ab)^2$", 0.5, r"\frac{1}{2}", BLUE, -6.3),
    ]
    fig, ax = plt.subplots(figsize=(4.6, 3.3))
    lt = np.log10(t)
    for V, lab, lam, frac, c, x0 in curves:
        ax.plot(lt, np.log10(V), color=c, lw=1.6)
        ax.text(lt[0] + 0.1, np.interp(lt[0] + 1.4, lt, np.log10(V)) + 0.25, lab, color=c, ha="left", va="bottom")
        # slope triangle with the asymptotic slope lambda, just below the curve
        x1 = x0 + 1.2
        y0 = np.interp(x1, lt, np.log10(V)) - 0.45 - lam * 1.2
        ax.plot([x0, x1, x1], [y0, y0, y0 + lam * 1.2], color=c, lw=0.9)
        ax.text(x1 + 0.1, y0 + lam * 0.6, r"$%s$" % frac, color=c, fontsize=11.5, va="center")
    ax.set_xlabel(r"$\log_{10} t$"); ax.set_ylabel(r"$\log_{10} V(t)$")
    ax.set_xlim(-10.2, 0.2)
    ax.text(-10, 0.3, r"slope $\to\lambda$ as $t\to0$", fontsize=12.5, va="top")
    bare(ax)
    save(fig, "logV")


# ------------------------------------------------------------------ poles and terms
def poles():
    fig, ax = plt.subplots(figsize=(7.0, 3.3))
    ax.set_xlim(-5.9, 1.3); ax.set_ylim(-2.75, 1.0); ax.axis("off")
    lam = [0.95, 3.0, 4.75]
    ax.add_patch(Rectangle((-lam[0], -0.5), lam[0] + 1.3, 1.2, color=BLUE, alpha=0.10, lw=0))
    ax.text(0.65, 0.5, r"$\int K^z\varphi$" "\nconverges", ha="center", va="center", color=BLUE, fontsize=11.5,
            linespacing=1.0)
    ax.annotate("", xy=(1.28, 0), xytext=(-5.85, 0), arrowprops=dict(arrowstyle="->", color=INK, lw=0.9))
    ax.plot([0, 0], [-0.45, 0.65], color=GREY, lw=0.8)
    ax.text(0.06, -0.22, r"$0$", color=GREY, fontsize=11.5)
    ax.text(1.28, -0.12, r"$\mathrm{Re}\,z$", ha="right", va="top", fontsize=11.5)
    ax.text(-5.85, 0.75, r"poles of $\zeta(z)$", ha="left", va="center", fontsize=12.5)
    labels = [r"$-\lambda$, order $m$", r"$-\lambda_2$, order $m_2$", r"$\cdots$"]
    for x, lab in zip(lam, labels):
        ax.plot(-x, 0, marker="x", ms=10, mew=2.2, color=ORANGE)
        ax.text(-x, 0.2, lab, ha="center", va="bottom", fontsize=11.5, color=ORANGE)
    rows = [
        (-1.2, r"small-$t$ terms of $v(t)$",
         [r"$c\,t^{\lambda-1}(-\log t)^{m-1}$", r"$c_2\,t^{\lambda_2-1}(-\log t)^{m_2-1}$", r"$\cdots$"]),
        (-2.15, r"large-$n$ terms of $\bar Z_n$",
         [r"$c'\,n^{-\lambda}(\log n)^{m-1}$", r"$c_2'\,n^{-\lambda_2}(\log n)^{m_2-1}$", r"$\cdots$"]),
    ]
    for y, head, terms in rows:
        ax.text(-5.85, y + 0.32, head, ha="left", va="center", fontsize=11.5, color=GREY)
        for x, term in zip(lam, terms):
            ax.text(-x, y, term, ha="center", va="center", fontsize=12.5)
    for x in lam[:2]:
        for y0, y1 in ((-0.3, -0.95), (-1.42, -1.92)):
            ax.add_patch(FancyArrowPatch((-x, y0), (-x, y1), arrowstyle="<->", mutation_scale=9, color=GREY, lw=0.8))
    ax.text(-lam[0], -2.6, r"$\Rightarrow\ \bar F_n\approx\lambda\log n-(m-1)\log\log n$", ha="center", va="center",
            fontsize=12, color=BLUE)
    save(fig, "poles")


# ------------------------------------------------------------------ two basins
def two_basins():
    # the same loss as the notebook's code cell, with delta = 0.03 so the gap is visible
    delta = 0.03
    w = np.linspace(-2.0, 2.5, 1501)
    x = np.clip(w + 0.5, 0, 1)
    K = (w + 1) ** 2 * (w - 1) ** 4 + delta * x**3 * (10 - 15 * x + 6 * x**2)   # smooth step, flat on both basins
    fig, axs = plt.subplots(3, 1, figsize=(6.0, 4.6), sharex=True,
                            gridspec_kw={"height_ratios": [1.5, 1, 1], "hspace": 0.15})
    ax = axs[0]
    ax.plot(w, K, color=INK, lw=1.6)
    ax.set_ylim(-0.015, 0.25); ax.set_yticks([]); ax.set_ylabel(r"$K(w)$")
    ax.text(-0.78, 0.13, "accurate, narrow\n" r"$U$: $K=0$, $\lambda_U=\frac{1}{2}$", ha="left", va="center",
            fontsize=11.5, color=BLUE)
    ax.text(1.55, 0.12, "less accurate, wide\n" r"$V$: $K=\Delta L$, $\lambda_V=\frac{1}{4}$", ha="left",
            va="center", fontsize=11.5, color=ORANGE)
    for y in (0.0, delta):
        ax.plot([-1.0, 0.5] if y == 0 else [0.4, 1.0], [y, y], color=GREY, lw=0.6, ls=":")
    ax.annotate("", xy=(0.45, delta), xytext=(0.45, 0.0),
                arrowprops=dict(arrowstyle="<->", color=INK, lw=0.7, mutation_scale=7, shrinkA=0, shrinkB=0))
    ax.text(0.39, delta / 2, r"$\Delta L$", ha="right", va="center", fontsize=11.5)
    bare(ax)
    for ax, n in zip(axs[1:], (10, 300)):
        lp = -n * K
        p = np.exp(lp - lp.max())
        mass_V = p[w > 0].sum() / p.sum()
        ax.fill_between(w, 0, p, where=w <= 0, color=BLUE, alpha=0.55, lw=0)
        ax.fill_between(w, 0, p, where=w > 0, color=ORANGE, alpha=0.55, lw=0)
        ax.plot(w, p, color=INK, lw=0.6)
        ax.set_ylim(0, 1.15); ax.set_yticks([])
        ax.set_ylabel(r"$n=%d$" % n, rotation=0, ha="right", va="center")
        side = "wide basin $V$" if mass_V > 0.5 else "narrow basin $U$"
        frac = max(mass_V, 1 - mass_V)
        txt = (r"posterior: %.0f%% of mass in %s" % (100 * frac, side) if frac < 0.995
               else r"posterior: $\approx$100%% of mass in %s" % side)
        ax.text(2.5, 0.95, txt, ha="right", va="center", fontsize=11.5)
        bare(ax)
    axs[-1].set_xticks([]); axs[-1].set_xlabel(r"parameter $w$")
    save(fig, "two_basins")


